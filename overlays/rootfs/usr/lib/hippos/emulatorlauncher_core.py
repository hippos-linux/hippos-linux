def _write_mupen_config(ctx: LaunchContext) -> None:
    conf = _load_effective_hippos_conf()
    profiles = _load_es_input_configs()
    MUPEN_CONFIG_DIR.mkdir(parents=True, exist_ok=True)
    parser = _new_ini_parser()
    if MUPEN_CUSTOM.exists():
        parser.read(MUPEN_CUSTOM)

    _ensure_section(parser, 'Core')
    _ensure_section(parser, 'Audio-SDL')
    _ensure_section(parser, 'Video-General')
    _ensure_section(parser, 'Video-Glide64mk2')
    _ensure_section(parser, 'Video-GLideN64')
    _ensure_section(parser, 'Video-Rice')
    _ensure_section(parser, '64DD')

    parser.set('Core', 'Version', '1.01')
    parser.set('Core', 'ScreenshotPath', str(SCREENSHOTS))
    parser.set('Core', 'SaveStatePath', str(SAVES / 'n64'))
    parser.set('Core', 'SaveSRAMPath', str(SAVES / 'n64'))
    parser.set('Core', 'SharedDataPath', str(MUPEN_CONFIG_DIR))
    parser.set('Core', 'SaveFilenameFormat', '1000')
    parser.set('Core', 'DisableExtraMem', str(_conf_bool(conf, 'mupen64plus_DisableExtraMem', False)))

    state_slot = _conf_value(conf, 'state_slot', '')
    if state_slot:
        parser.set('Core', 'CurrentStateSlot', state_slot)
    parser.set('Core', 'AutoStateSlotIncrement', str(_conf_bool(conf, 'incrementalsavestates', True)))

    parser.set('Audio-SDL', 'AUDIO_SYNC', str(_conf_bool(conf, 'mupen64plus_AudioSync', False)))
    match _conf_value(conf, 'mupen64plus_AudioBuffer', 'Medium'):
        case 'Very High':
            primary_buffer_size = '16384'
            primary_buffer_target = '4096'
            secondary_buffer_size = '2048'
        case 'High':
            primary_buffer_size = '16384'
            primary_buffer_target = '2048'
            secondary_buffer_size = '1024'
        case 'Low':
            primary_buffer_size = '4096'
            primary_buffer_target = '1024'
            secondary_buffer_size = '512'
        case _:
            primary_buffer_size = '8192'
            primary_buffer_target = '2048'
            secondary_buffer_size = '1024'
    parser.set('Audio-SDL', 'PRIMARY_BUFFER_SIZE', primary_buffer_size)
    parser.set('Audio-SDL', 'PRIMARY_BUFFER_TARGET', primary_buffer_target)
    parser.set('Audio-SDL', 'SECONDARY_BUFFER_SIZE', secondary_buffer_size)

    display_resolution = _display_resolution_from_conf(conf)
    if display_resolution is not None:
        width, height = display_resolution
        if width < height:
            width, height = height, width
        parser.set('Video-General', 'ScreenWidth', str(width))
        parser.set('Video-General', 'ScreenHeight', str(height))
    parser.set('Video-General', 'Version', '1')
    parser.set('Video-General', 'Fullscreen', 'False')
    parser.set('Video-General', 'VerticalSync', 'True')

    parser.set('Video-Rice', 'Version', '1')
    parser.set('Video-Glide64mk2', 'Version', '1')

    mupen_ratio = _conf_value(conf, 'mupen64plus_ratio', '')
    ratio = _conf_value(conf, 'global.ratio', 'core')
    if mupen_ratio == '16/9' or (not mupen_ratio and ratio == '16/9'):
        adjust_aspect = '1'
        aspect = '1'
        aspect_ratio = '2'
    elif mupen_ratio == '4/3' or (not mupen_ratio and ratio == '4/3'):
        adjust_aspect = '0'
        aspect = '0'
        aspect_ratio = '1'
    else:
        adjust_aspect = '-1'
        aspect = '-1'
        aspect_ratio = '3'
    parser.set('Video-Glide64mk2', 'adjust_aspect', adjust_aspect)
    parser.set('Video-Glide64mk2', 'aspect', aspect)
    parser.set('Video-GLideN64', 'AspectRatio', aspect_ratio)

    match _conf_value(conf, 'mupen64plus_Mipmapping', '0'):
        case '1':
            filtering = '0'
        case '2':
            filtering = '1'
        case '3':
            filtering = '2'
        case _:
            filtering = '-1'
    parser.set('Video-Rice', 'Mipmapping', _conf_value(conf, 'mupen64plus_Mipmapping', '0'))
    parser.set('Video-Glide64mk2', 'filtering', filtering)

    anisotropic = _conf_value(conf, 'mupen64plus_Anisotropic', '0')
    parser.set('Video-Rice', 'AnisotropicFiltering', anisotropic)
    parser.set('Video-Glide64mk2', 'wrpAnisotropic', '1' if anisotropic == '0' else anisotropic)

    antialiasing = _conf_value(conf, 'mupen64plus_AntiAliasing', '0')
    parser.set('Video-Rice', 'MultiSampling', antialiasing)
    parser.set('Video-Glide64mk2', 'wrpAntiAliasing', antialiasing)

    load_hires_textures = _conf_bool(conf, 'mupen64plus_LoadHiResTextures', False)
    parser.set('Video-Rice', 'LoadHiResTextures', str(load_hires_textures))
    parser.set('Video-Glide64mk2', 'ghq_hirs', '1' if load_hires_textures else '0')
    parser.set('Video-Rice', 'TextureEnhancement', _conf_value(conf, 'mupen64plus_TextureEnhancement', '0'))

    autoframeskip = '0'
    parser.set('Video-Glide64mk2', 'autoframeskip', '0')
    match _conf_value(conf, 'mupen64plus_frameskip', '0'):
        case 'automatic':
            autoframeskip = '1'
            maxframeskip = '5'
        case '0':
            maxframeskip = '0'
        case _ as frameskip:
            maxframeskip = frameskip
    parser.set('Video-Glide64mk2', 'autoframeskip', autoframeskip)
    parser.set('Video-Glide64mk2', 'maxframeskip', maxframeskip)
    parser.set('Video-Glide64mk2', 'fb_read_always', _conf_value(conf, 'mupen64plus_fb_read_always', '-1'))

    if ctx.system == 'n64dd':
        parser.set('64DD', 'IPL-ROM', str(BIOS / '64DD_IPL.bin'))
    else:
        parser.set('64DD', 'IPL-ROM', '')
    parser.set('64DD', 'Disk', '')

    parser.set('Video-Rice', 'ShowFPS', 'True' if _conf_bool(conf, 'show_fps', False) else 'False')
    parser.set('Video-Glide64mk2', 'show_fps', '4' if _conf_bool(conf, 'show_fps', False) else '8')

    for section_option, user_config_value in conf.items():
        if not section_option.startswith('mupen64plus.'):
            continue
        custom_section, _, custom_option = section_option.partition('.')
        _ensure_section(parser, custom_section)
        parser.set(custom_section, custom_option, str(user_config_value))

    _write_mupen_controller_configs(ctx, profiles, parser, conf)

    with MUPEN_CUSTOM.open('w', encoding='utf-8') as fh:
        parser.write(fh)

    _log.info("Wrote Mupen config: %s", MUPEN_CUSTOM)


