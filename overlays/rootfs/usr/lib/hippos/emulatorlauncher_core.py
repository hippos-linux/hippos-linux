def _write_mame_config(conf: dict[str, str]) -> None:
    MAME_CONFIG_DIR.mkdir(parents=True, exist_ok=True)
    (SAVES / 'mame').mkdir(parents=True, exist_ok=True)

    lines: list[tuple[str, str]] = [
        ('inipath',            f'{MAME_CONFIG_DIR};/etc/mame'),
        ('rompath',            f'{MAME_ROMS};/usr/share/games/mame/roms'),
        ('cfg_directory',      str(MAME_CONFIG_DIR / 'cfg')),
        ('nvram_directory',    str(SAVES / 'mame' / 'nvram')),
        ('snapshot_directory', str(SCREENSHOTS)),
        ('state_directory',    str(SAVES / 'mame')),
        ('video',              'opengl'),
        ('window',             '0'),
        ('mouse',              '1'),
    ]

    if Path('/etc/switchres.ini').exists():
        profile    = conf.get('crt.monitor_profile', 'generic_15')
        sw         = conf.get('crt.super_width',     '2560')
        dotclk     = conf.get('crt.dotclock_min',    '0.0')
        lines += [
            ('switchres',    '1'),
            ('monitor',      profile),
            ('super_width',  sw),
            ('dotclock_min', dotclk),
        ]

    col = max(len(k) for k, _ in lines) + 3
    with MAME_INI.open('w') as fh:
        fh.write('# Generated by emulatorlauncher — do not edit manually.\n')
        for key, value in lines:
            fh.write(f'{key:<{col}}{value}\n')



def launch_mame(ctx: LaunchContext) -> int:
    bin_path = _find_emulator_bin('mame')
    if bin_path is None:
        return 1

    conf = _load_hippos_conf()
    _write_mame_config(conf)
    (SAVES / ctx.system).mkdir(parents=True, exist_ok=True)

    from emulatorlauncher_mame_controllers import generate_mame_pads_config
    cfg_dir = MAME_CONFIG_DIR / 'cfg'
    try:
        generate_mame_pads_config(cfg_dir, ctx, conf)
    except Exception as exc:
        _log.warning("MAME controller config failed: %s", exc)

    game_flags: list[str] = []
    if ctx.lightgun:
        game_flags += ['-lightgunprovider', 'udev', '-lightgun_device', 'lightgun', '-adstick_device', 'lightgun']
    elif ctx.wheel:
        game_flags += ['-dial_device', 'mouse', '-trackball_device', 'mouse', '-paddle_device', 'mouse', '-positional_device', 'mouse', '-mouse_device', 'mouse', '-ui_mouse']

    cmd = [str(bin_path), '-inipath', f'{MAME_CONFIG_DIR};/etc/mame', *game_flags, str(ctx.rom)]
    env = _build_game_env(conf, ctx)
    result = _run_game_command(ctx, 'mame', cmd, env)
    return result.returncode



