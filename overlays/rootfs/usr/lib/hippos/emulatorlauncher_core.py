def _write_mame_config(conf: dict[str, str]) -> None:
    MAME_CONFIG_DIR.mkdir(parents=True, exist_ok=True)
    (SAVES / 'mame').mkdir(parents=True, exist_ok=True)

    lines: list[tuple[str, str]] = [
        ('inipath',            f'{MAME_CONFIG_DIR};/etc/mame'),
        ('rompath',            f'{MAME_ROMS};/usr/share/games/mame/roms'),
        ('cfg_directory',      str(MAME_CONFIG_DIR / 'cfg')),
        ('nvram_directory',    str(SAVES / 'mame' / 'nvram')),
        ('input_directory',    str(SAVES / 'mame' / 'input')),
        ('state_directory',    str(SAVES / 'mame' / 'state')),
        ('diff_directory',     str(SAVES / 'mame' / 'diff')),
        ('comment_directory',  str(SAVES / 'mame' / 'comments')),
        ('snapshot_directory', str(SCREENSHOTS)),
        ('video',              'opengl'),
        ('window',             '0'),
        ('mouse',              '1'),
        ('joystickprovider',   'sdljoy'),
    ]

    if Path('/etc/switchres.ini').exists():
        profile    = conf.get('crt.monitor_profile', 'generic_15')
        sw         = conf.get('crt.super_width',     '2560')
        dotclk     = conf.get('crt.dotclock_min',    '0.0')
        tate       = conf.get('crt.tate_mode',       'off').strip().lower()
        lines += [
            ('switchres',        '1'),
            ('switchres_ini',    '1'),
            ('monitor',          profile),
            ('super_width',      sw),
            ('dotclock_min',     dotclk),
            ('h_size',           '1.0'),
            ('h_shift',          '0'),
            ('v_shift',          '0'),
            ('v_shift_correct',  '0'),
            ('pixel_precision',  '1'),
        ]
        if tate == 'ror':
            lines += [('rotate', '1'), ('autoror', '1')]
        elif tate == 'rol':
            lines += [('rotate', '1'), ('autorol', '1')]
    else:
        lines += [
            ('switchres',           '0'),
            ('modeline_generation', '0'),
            ('changeres',           '0'),
        ]

    col = max(len(k) for k, _ in lines) + 3
    with MAME_INI.open('w') as fh:
        fh.write('# Generated by emulatorlauncher - do not edit manually.\n')
        for key, value in lines:
            fh.write(f'{key:<{col}}{value}\n')

@dataclass(frozen=True)
class _MessMachine:
    machine: str
    media: str
    autoboot: str

@cache
def _mess_machines() -> dict[str, _MessMachine]:
    machines = {}
    with (EMULATORLAUNCHER_DATA_DIR / 'mame' / 'messSystems.csv').open(encoding='utf-8') as fh:
        for row in csv.reader(fh, delimiter=';', quotechar="'"):
            if len(row) >= 3 and row[1]:
                machines[row[0]] = _MessMachine(row[1], row[2], row[3] if len(row) > 3 else '')
    return machines

_MESS_MEDIA_BY_EXTENSION: dict[str, dict[str, str]] = {
    'adam':     {'.ddp': 'cass1', '.dsk': 'flop1'},
    'coco':     {'.cas': 'cass', '.dsk': 'flop1'},
    'dragon64': {'.cas': 'cass', '.dsk': 'flop1'},
    'mc10':     {'.cas': 'cass'},
    'sc3000':   {'.cas': 'cass', '.wav': 'cass', '.bit': 'cass'},
    'segaai':   {'.wav': 'cass', '.flac': 'cass', '.cas': 'cass'},
}
_MESS_MACHINE_OPTIONS: dict[str, list[str]] = {
    'enterprise': ['-exp', 'exdos'],
}
_MESS_MEDIA_DEFAULT: dict[str, str] = {'adam': 'cart1', 'coco': 'cart', 'dragon64': 'cart', 'mc10': 'cart', 'sc3000': 'cart'}

def _mess_args(system: str, rom: Path) -> list[str] | None:
    mess = _mess_machines().get(system)
    if mess is None:
        return None
    ext = rom.suffix.lower()
    media = _MESS_MEDIA_BY_EXTENSION.get(system, {}).get(ext) or _MESS_MEDIA_DEFAULT.get(system) or mess.media
    args = [mess.machine, *_MESS_MACHINE_OPTIONS.get(system, []), f'-{media}', str(rom)]
    if mess.autoboot:
        args += ['-autoboot_delay', '3', '-autoboot_command', mess.autoboot]
    return args

def launch_mame(ctx: LaunchContext) -> int:
    bin_path = _require_emulator_bin('mame')

    conf = _load_hippos_conf()
    _write_mame_config(conf)
    (SAVES / ctx.system).mkdir(parents=True, exist_ok=True)

    from emulatorlauncher_mame_controllers import generate_mame_pads_config
    cfg_dir = MAME_CONFIG_DIR / 'cfg'
    try:
        generate_mame_pads_config(cfg_dir, ctx, conf)
    except Exception as exc:
        _log.warning("MAME controller config failed: %s", exc)

    game_flags: list[str] = []
    if ctx.lightgun:
        game_flags += ['-lightgunprovider', 'udev', '-lightgun_device', 'lightgun', '-adstick_device', 'lightgun']
    elif ctx.wheel:
        game_flags += ['-dial_device', 'mouse', '-trackball_device', 'mouse', '-paddle_device', 'mouse', '-positional_device', 'mouse', '-mouse_device', 'mouse', '-ui_mouse']

    rompath = ';'.join(str(p) for p in (ctx.rom.parent, BIOS, BIOS / 'mame', MAME_ROMS))
    cmd = [str(bin_path), '-skip_gameinfo', '-inipath', f'{MAME_CONFIG_DIR};/etc/mame', '-rompath', rompath, *game_flags]
    cmd += _mess_args(ctx.system, ctx.rom) or [str(ctx.rom)]
    env = _build_game_env(conf, ctx)
    result = _run_game_command(ctx, cmd, env)
    return result.returncode

